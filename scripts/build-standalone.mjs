import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/standalone.tsx'],
  outfile: 'standalone.js',
  bundle: true,
  write: false,
  minify: true,
  legalComments: 'inline',
  platform: 'browser',
  format: 'iife',
  target: ['es2022'],
  define: { 'process.env.NODE_ENV': '"production"' },
});
const js = result.outputFiles.find((file) => file.path.endsWith('.js')).text;
const css = result.outputFiles.find((file) => file.path.endsWith('.css')).text;
const favicon = await readFile(resolve(root, 'public/favicon.svg'), 'utf8');
const html = `<!doctype html>
<!-- Generated by npm run build:standalone. Edit src/ and shared/, then rebuild. -->
<html lang="ko"><head>
<meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="theme-color" content="#174d39">
<meta name="description" content="관심사와 준비물에 맞는 과학 실험을 찾아보세요. 설치 없이 열 수 있는 실험실.">
<title>실험실 — 호기심이 실험이 되는 곳</title>
<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,${encodeURIComponent(favicon)}">
<style>${css.replace(/<\/style/gi, '<\\/style')}</style>
</head><body><div id="root"></div>
<noscript>실험실을 사용하려면 브라우저의 JavaScript를 허용해 주세요.</noscript>
<script>${js.replace(/<\/script/gi, '<\\/script')}</script>
</body></html>\n`;
await writeFile(resolve(root, 'index.html'), html);
console.log(
  `Standalone index.html generated (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB). No server or external assets required.`,
);
